def area(r):
    """
    Вычисляет площадь круга по радиусу r.

    Параметры:
        r (float): радиус круга

    Возвращает:
        float: площадь круга

    Пример:
        >>> area(5)
        78.5
    """
    return 3.14 * r * r


def perimeter(r):
    """
    Вычисляет длину окружности по радиусу r.

    Параметры:
        r (float): радиус круга

    Возвращает:
        float: длина окружности

    Пример:
        >>> perimeter(5)
        31.4
    """
    return 2 * 3.14 * r




